static const uint8_t *glyph_rows(char c)
{
    const char upper = (char)toupper((unsigned char)c);
    for (size_t i = 0; i < sizeof(g_glyphs) / sizeof(g_glyphs[0]); i++) {
        if (g_glyphs[i].c == upper) {
            return g_glyphs[i].rows;
        }
    }
    return 0;
}

int ui_text_width(int scale, const char *text)
{
    const size_t length = strlen(text);
    if (length == 0) {
        return 0;
    }
    return (int)(length * UI_TEXT_ADVANCE - 1) * scale;
}

int ui_text_height(int scale)
{
    return UI_TEXT_GLYPH_H * scale;
}

void ui_text_draw(SDL_Renderer *renderer, int x, int y, int scale, const char *text)
{
    int pen_x = x;
    for (const char *p = text; *p != '\0'; p++) {
        const uint8_t *rows = glyph_rows(*p);
        if (rows != 0) {
            for (int row = 0; row < UI_TEXT_GLYPH_H; row++) {
                for (int col = 0; col < UI_TEXT_GLYPH_W; col++) {
                    if ((rows[row] & (0x10U >> col)) != 0U) {
                        const SDL_Rect dot = {
                            .x = pen_x + col * scale,
                            .y = y + row * scale,
                            .w = scale,
                            .h = scale,
                        };
                        SDL_RenderFillRect(renderer, &dot);
                    }
                }
            }
        } else if (*p != ' ') {
            /* Unknown glyph: hollow box. */
            const SDL_Rect box = {.x = pen_x, .y = y, .w = UI_TEXT_GLYPH_W * scale, .h = UI_TEXT_GLYPH_H * scale};
            SDL_RenderDrawRect(renderer, &box);
        }
        pen_x += UI_TEXT_ADVANCE * scale;
    }
}
